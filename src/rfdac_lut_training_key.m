function key=rfdac_lut_training_key(c,p)
% All physical/stimulus settings that can change the measured constellation.
% DPD model estimates are deliberately excluded: the measured LUT ignores them.
fields={'Model_Name','Sample_Rate','DAC_Sample_Rate','Symbol_Rate','DAC_Bits', ...
    'DAC_Full_Scale','Input_Amplitude','RRC_Rolloff','RRC_Span', ...
    'LPF_Cutoff','LPF_Order','RX_LPF_Cutoff','RX_LPF_Order', ...
    'LO_Frequency','LO_Jitter_Enable','LO_RMS_Jitter','Jitter_Mode','Jitter_Bandwidth', ...
    'LO_Quadrature_Error_Enable','LO_Quadrature_Error_Deg','LO_Phase_Errors_Deg', ...
    'RX_LO_Mode','RX_LO_Frequency','RX_LO_Phase','RX_LO_RMS_Jitter', ...
    'RX_Equalizer_Enable','RX_Equalizer_Order','RX_Equalizer_Max_Boost_dB', ...
    'RX_Equalizer_Regularization', ...
    'DPD_LUT_Training_Repeats','DPD_LUT_Training_Seed','DPD_LUT_Drive_Range', ...
    'DPD_LUT_Training_Dwell_Samples','DPD_LUT_Training_Prefix_Zeros'};
key=struct('Version',3,'Physical_Beta',p.TX_Beta, ...
    'Observation_Domain','phase_aligned_equalized_RX_envelope_V');
for k=1:numel(fields), key.(fields{k})=c.(fields{k}); end
% Zero offsets have exactly the historical physical response and key.
loFields={'LO_Differential_Phase_Error_Deg','LO_Quadrature_Amplitude_Mismatch'};
for k=1:numel(loFields)
    field=loFields{k};
    if c.LO_Quadrature_Error_Enable && isfield(c,field) && c.(field)~=0
        key.(field)=c.(field);
    end
end
key.Drive_I=p.DPD.LUT.Training_I; key.Drive_Q=p.DPD.LUT.Training_Q;
end
